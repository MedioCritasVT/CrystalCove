#!/usr/bin/env python3
"""Local-only, opt-in Bazzite media mirror installer. No sudo, no migration."""
from __future__ import annotations
import os
import secrets
import shutil
import socket
import subprocess
import sys
import time
from pathlib import Path

ROOT = Path.home() / ".local" / "share" / "conflux-media-mirror"
UNITS = Path.home() / ".config" / "containers" / "systemd"
SERVICES = {
    "jellyfin": {
        "port": 8096, "image": "docker.io/jellyfin/jellyfin:latest",
        "mounts": [("state/jellyfin/config", "/config", "Z"),
                   ("state/jellyfin/cache", "/cache", "Z"),
                   ("media/video", "/media", "ro,z")]},
    "navidrome": {
        "port": 4533, "image": "docker.io/navidrome/navidrome:latest",
        "mounts": [("state/navidrome/data", "/data", "Z"),
                   ("media/music", "/music", "ro,z")]},
    "kavita": {
        "port": 5000, "image": "ghcr.io/kareadita/kavita:latest",
        "mounts": [("state/kavita/config", "/kavita/config", "Z"),
                   ("media/books", "/books", "ro,z"),
                   ("media/comics", "/comics", "ro,z"),
                   ("media/manga", "/manga", "ro,z")]},
}
SUPPORTED = tuple(SERVICES)
PLAN_WINDOW = 300
_issued = {}

def read_os_release(path=Path("/etc/os-release")):
    try:
        lines = path.read_text(encoding="utf-8").splitlines()
    except OSError:
        return {}
    data = {}
    for line in lines:
        if "=" in line and not line.lstrip().startswith("#"):
            k, v = line.split("=", 1)
            if k in {"ID", "VARIANT_ID", "IMAGE_ID", "PRETTY_NAME"}:
                data[k] = v.strip().strip('"').strip("'")
    return data

def on_bazzite(info=None):
    data = info if info is not None else read_os_release()
    return any("bazzite" in data.get(k, "").lower()
               for k in ("ID", "VARIANT_ID", "IMAGE_ID"))

def command_available(cmd):
    return shutil.which(cmd) is not None

def run_readonly(argv, timeout=12):
    try:
        p = subprocess.run(argv, capture_output=True, text=True,
                           check=False, timeout=timeout)
        return p.returncode == 0, (p.stdout or p.stderr).strip()[:500]
    except (OSError, subprocess.TimeoutExpired):
        return False, "Command unavailable or timed out"

def port_free(port):
    try:
        with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as s:
            s.bind(("127.0.0.1", port))
        return True
    except OSError:
        return False

def file_for(name):
    if name not in SERVICES:
        raise ValueError("Unknown service")
    return UNITS / ("conflux-media-" + name + ".container")

def unit_for(name):
    spec = SERVICES[name]
    lines = [
        "# Generated by Conflux Bazzite Mirror installer; no automatic image updates.",
        "[Unit]", "Description=Conflux media mirror: " + name,
        "[Container]", "Image=" + spec["image"],
        "ContainerName=conflux-media-" + name,
        "PublishPort=127.0.0.1:%s:%s/tcp" % (spec["port"], spec["port"]),
        "UserNS=keep-id",
    ]
    # Rootless user mounts are private to this fresh secondary installation.
    for rel, dest, opts in spec["mounts"]:
        lines.append("Volume=" + str(ROOT / rel) + ":" + dest + ":" + opts)
    lines += ["[Service]", "Restart=on-failure", "TimeoutStartSec=300",
              "[Install]", "WantedBy=default.target"]
    return "\n".join(lines) + "\n"

def summarize():
    info = read_os_release()
    checks = {
        "bazzite": on_bazzite(info),
        "podman": command_available("podman"),
        "systemctl": command_available("systemctl"),
        "python": sys.version_info >= (3, 10),
        "rootless_user": os.geteuid() != 0,
    }
    if checks["podman"]:
        checks["podman_rootless"] = run_readonly(
            ["podman", "info", "--format", "{{.Host.Security.Rootless}}"])[0]
    else:
        checks["podman_rootless"] = False
    if checks["systemctl"]:
        checks["user_systemd"] = run_readonly(
            ["systemctl", "--user", "show-environment"])[0]
    else:
        checks["user_systemd"] = False
    services = {}
    for name, spec in SERVICES.items():
        path = file_for(name)
        # Never overwrite even a partial previous installation.
        services[name] = {
            "port": spec["port"], "image": spec["image"],
            "unit_conflict": path.exists() or path.is_symlink(),
            "port_free": port_free(spec["port"]),
            "state_conflict": (ROOT / "state" / name).exists(),
        }
    checks["all_requirements"] = all(checks.values())
    ready = checks["all_requirements"] and all(
        not value["unit_conflict"] and value["port_free"] and
        not value["state_conflict"] for value in services.values())
    return {"host": info.get("PRETTY_NAME", info.get("ID", "unknown")),
            "checks": checks, "services": services, "ready": ready,
            "existing_data_untouched": True,
            "immich": "Not included: official Immich requires a separately reviewed Docker Compose/database deployment.",
            "searxng": "Not included in the first installer: its private configuration and update model need a separate review.",
            "scope": "New isolated localhost-only services; no existing library imports, no sudo, no package layering, no automatic updates."}

def issue_plan():
    report = summarize()
    _issued.clear()
    if report["ready"]:
        token = secrets.token_urlsafe(24)
        _issued[token] = time.monotonic() + PLAN_WINDOW
        report["plan_token"] = token
    return report

def install(plan_token, explicit_confirmation):
    if not isinstance(plan_token, str) or not isinstance(explicit_confirmation, str):
        raise ValueError("Missing approval information")
    if explicit_confirmation != "INSTALL NEW BAZZITE MIRROR":
        raise ValueError("Confirmation phrase did not match")
    expiry = _issued.pop(plan_token, None)
    if expiry is None or time.monotonic() > expiry:
        raise ValueError("Plan expired. Run the dependency check again")
    fresh = summarize()
    if not fresh["ready"]:
        raise ValueError("Host requirements, ports, or files changed; plan again")
    # No host package installation or elevated privileges. The user explicitly
    # requests these new services; live instances and data are never imported.
    created_files = []
    created_dirs = []
    try:
        dirs = sorted({ROOT / rel for spec in SERVICES.values()
                       for rel, _, _ in spec["mounts"]}, key=lambda p: len(p.parts))
        for directory in dirs:
            if directory.exists() or directory.is_symlink():
                raise ValueError("Data destination already exists: " + str(directory))
            directory.mkdir(parents=True, exist_ok=False)
            created_dirs.append(directory)
        UNITS.mkdir(parents=True, exist_ok=True)
        for name in SUPPORTED:
            target = file_for(name)
            # x excludes accidental overwrites (including pre-existing symlinks).
            with target.open("x", encoding="utf-8") as handle:
                handle.write(unit_for(name))
            created_files.append(target)
        ok, message = run_readonly(["systemctl", "--user", "daemon-reload"], timeout=15)
        if not ok:
            raise RuntimeError("systemd generator reload failed: " + message)
    except Exception:
        for file in reversed(created_files):
            file.unlink(missing_ok=True)
        # Preserve any potential service data after the first successful reload.
        # Empty new directories may be left for manual inspection.
        raise
    results = {}
    for name in SUPPORTED:
        # Starting may pull official images; individual services can fail
        # without deleting configs or affecting existing services.
        ok, detail = run_readonly(
            ["systemctl", "--user", "start", "conflux-media-" + name + ".service"],
            timeout=310)
        results[name] = {"started": ok, "detail": detail[:300],
                         "url": "http://127.0.0.1:%d" % SERVICES[name]["port"]}
    return {"installed_files": [str(f) for f in created_files],
            "services": results, "all_started": all(x["started"] for x in results.values()),
            "warning": "New empty libraries only. Verify every service locally; no backups, media imports or remote access were configured."}

if __name__ == "__main__":
    import argparse, json
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true", help="Read-only inventory (default)")
    args = ap.parse_args()
    print(json.dumps(summarize(), indent=2))
